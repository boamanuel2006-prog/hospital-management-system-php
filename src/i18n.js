export function getTranslator(lang) {
  const dict = translations[lang === 'pt' ? 'pt' : 'en'];
  return (keyPath) => {
    const parts = String(keyPath).split('.');
    let cur = dict;
    for (const p of parts) {
      if (cur && Object.prototype.hasOwnProperty.call(cur, p)) {
        cur = cur[p];
      } else {
        return keyPath;
      }
    }
    return cur;
  };
}

export function translateStatus(lang, status) {
  const dict = translations[lang === 'pt' ? 'pt' : 'en'];
  return dict.status[status] || status;
}
